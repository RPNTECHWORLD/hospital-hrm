/**
 * Normalizes patient address to a canonical registered location + pincode format.
 * Returns string such as "Kollidam (609102)", "Chidambaram (608001)", "Sirkazhi (609110)".
 */
export const resolvePatientLocation = (address) => {
  if (!address || typeof address !== 'string') return 'Not Specified';
  const trimmed = address.trim();
  if (!trimmed) return 'Not Specified';

  // 1. Extract 6-digit Pincode
  const pinMatch = trimmed.match(/\b([1-9]\d{5})\b/);
  const pincode = pinMatch ? pinMatch[1] : '';

  // If pincode is found in registered master map
  if (pincode && PINCODE_REGISTERED_MAP[pincode]) {
    const regName = PINCODE_REGISTERED_MAP[pincode];
    return `${regName} (${pincode})`;
  }

  // 2. Parse text components (if pipe-separated "Area | City | Pincode")
  let extractedName = '';
  if (trimmed.includes(' | ')) {
    const parts = trimmed.split(' | ').map(s => s.trim()).filter(Boolean);
    // Use City (part 1) if available and not numbers, else Area (part 0)
    if (parts.length >= 2 && parts[1] && !/^\d+$/.test(parts[1])) {
      extractedName = parts[1];
    } else if (parts[0] && !/^\d+$/.test(parts[0])) {
      extractedName = parts[0];
    }
  } else {
    // Single string address - clean out numbers and punctuation
    const cleanStr = trimmed.replace(/,\s*/g, ' ').replace(/\b\d{6}\b/g, '').trim();
    if (cleanStr) {
      const words = cleanStr.split(/\s+/).filter(w => !/^\d+$/.test(w) && w.length > 2);
      if (words.length > 0) {
        extractedName = words.slice(-2).join(' ');
      }
    }
  }

  if (!extractedName) {
    return pincode ? `Pincode ${pincode}` : 'Not Specified';
  }

  // 3. Check spelling normalization table
  const lowerExtracted = extractedName.toLowerCase().trim();
  if (LOCATION_TYPO_MAP[lowerExtracted]) {
    extractedName = LOCATION_TYPO_MAP[lowerExtracted];
  }

  // Capitalize properly
  const canonicalName = extractedName
    .split(' ')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(' ');

  // Return formatted with pincode if available
  if (pincode) {
    return `${canonicalName} (${pincode})`;
  }

  // If no pincode in address, try to check if canonicalName matches a known pincode in TN_LOCATIONS
  const matchedLoc = TN_LOCATIONS.find(loc =>
    loc.city.toLowerCase() === lowerExtracted ||
    loc.area.toLowerCase() === lowerExtracted
  );

  if (matchedLoc) {
    return `${matchedLoc.city} (${matchedLoc.pincode})`;
  }

  return canonicalName;
};
